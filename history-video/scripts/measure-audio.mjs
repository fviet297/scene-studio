// Measure each per-scene narration file and emit src/audio-durations.ts.
// The composition lays out one Sequence per scene from these real durations, so video
// length always matches the audio — no time-stretching, no guessed frame counts.
// Run after (re)generating audio: node scripts/measure-audio.mjs

import { execFileSync } from 'node:child_process';
import { existsSync, writeFileSync } from 'node:fs';
import { SEGMENTS } from '../../scripts/narration-segments.mjs';

const AUDIO_DIR = 'public/audio';
const OUTPUT = 'src/audio-durations.ts';

const probe = (file) =>
  Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'default=nw=1:nk=1', file], { encoding: 'utf8' }).trim());

const scenes = SEGMENTS.map((segment) => {
  const file = `${AUDIO_DIR}/scene-${String(segment.scene).padStart(2, '0')}.mp3`;
  if (!existsSync(file)) throw new Error(`missing audio ${file} — run generate-narration.mjs`);
  return { scene: segment.scene, seconds: Number(probe(file).toFixed(3)) };
});

const total = scenes.reduce((sum, s) => sum + s.seconds, 0);
writeFileSync(
  OUTPUT,
  `// Generated by scripts/measure-audio.mjs — real per-scene narration durations (seconds).\n`
  + `export const sceneDurations = ${JSON.stringify(scenes.map((s) => s.seconds))} as const;\n`,
);
process.stdout.write(`Measured ${scenes.length} scenes, total ${total.toFixed(3)}s → ${OUTPUT}\n`);
